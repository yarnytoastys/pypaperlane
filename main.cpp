#include <string>
#include <vector>

void small_factorial() {
    int result = 1;
    for (int i = 1; i <= 6; ++i) result *= i;
    (void)result;
}

void divisor_count() {
    int n = 36;
    int count = 0;
    for (int d = 1; d <= n; ++d) {
        if (n % d == 0) count += 1;
    }
    (void)count;
}

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void binomial_small() {
    int n = 6, k = 2;
    int result = 1;
    for (int i = 1; i <= k; ++i) result = result * (n - k + i) / i;
    (void)result;
}

extern "C" int cobalt_vale();
extern "C" void frost_canyon();
extern "C" void placid_willow();

int main() {
    small_factorial();
    divisor_count();
    sum_squares();
    binomial_small();
    frost_canyon();
    placid_willow();
    return cobalt_vale();
}
